# start server with ngrok
def start_server():
    nest_asyncio.apply()

    try:
        # Retrieve the token securely from the system environment variables
        NGROK_TOKEN = os.environ.get('NGROK_AUTHTOKEN')

        if not NGROK_TOKEN:
            print("❌ Error: 'NGROK_TOKEN' environment variable is missing.")
            print("Please make sure you are passing it from your host notebook cell.")
            return

        ngrok.set_auth_token(NGROK_TOKEN)
    except Exception as e:
        print(f"❌ Error setting ngrok token: {e}")
        return

    # Open ngrok tunnel on port 8000
    try:
        tunnel = ngrok.connect(8000)
        public_url = tunnel.public_url
    except Exception as e:
        print(f"❌ Error connecting to ngrok: {e}")
        return

    print("\n" + "="*50)
    print(f"  Public API URL:  {public_url}")
    print(f"  Health check:    {public_url}/")
    print(f"  Summarize:       {public_url}/summarize")
    print(f"  History:         {public_url}/history")
    print("="*50)
    print("\n  Copy the URL above into extension/background.js\n")

    # Start the FastAPI application via uvicorn
    uvicorn.run(app, host="0.0.0.0", port=8000)

# Run in a thread so Colab stays interactive
thread = threading.Thread(target=start_server, daemon=True)
thread.start()

